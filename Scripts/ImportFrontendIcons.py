"""Regenerate Qt vector geometry from the frontend's pinned lucide-react package.

Requires the frontend npm dependencies and fonttools (only when regenerating).
Normal C++ builds use the checked-in output, without Node/Python/QtSvg.
"""
import json
from pathlib import Path
import re

from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / 'engine-web-prototype/frontend'
PACKAGE = FRONTEND / 'node_modules/lucide-react'
OUTPUT = ROOT / 'Root/Editor/src/UI/Styles/FrontendIconPaths.inc'


class QtPen(BasePen):
    def __init__(self):
        super().__init__(None)
        self.lines = []

    def command(self, name, *points):
        self.lines.append('Path.' + name + '(' + ', '.join(f'{v:.9g}' for p in points for v in p) + ');')

    def _moveTo(self, p): self.command('moveTo', p)
    def _lineTo(self, p): self.command('lineTo', p)
    def _curveToOne(self, p1, p2, p3): self.command('cubicTo', p1, p2, p3)
    def _qCurveToOne(self, p1, p2): self.command('quadTo', p1, p2)
    def _closePath(self): self.lines.append('Path.closeSubpath();')
    def _endPath(self): pass


def main():
    version = json.loads((PACKAGE / 'package.json').read_text())['version']
    source = '\n'.join(p.read_text(encoding='utf-8') for p in (FRONTEND / 'src').rglob('*') if p.suffix in {'.js', '.jsx'})
    names = set(re.findall(r'[\'\"]([A-Z][A-Za-z0-9]+)[\'\"]', source))
    # Native semantic aliases, also used by shell, launcher and inspector.
    names.update('Flower2 Play Pause StepForward FolderOpen Move Rotate3D Scaling Box Video Lightbulb Search Maximize2 PanelRightClose Grid3X3 Plus Focus ChevronDown ChevronRight MessageSquare Layers ExternalLink Copy Trash2 Star MousePointer2 Magnet CircleHelp Sandwich'.split())
    identifiers = set(re.findall(r'\b[A-Z][A-Za-z0-9]+\b', source))
    exports = (PACKAGE / 'dist/esm/lucide-react.js').read_text()
    icons = {}
    for aliases, filename in re.findall(r"export \{ (.*?) \} from './icons/(.*?)';", exports):
        for name in re.findall(r'default as (\w+)', aliases):
            # Direct imports need no quotes around the icon name.
            if name in names or name in identifiers:
                icons[name] = filename
    lines = [f'// Generated by Scripts/ImportFrontendIcons.py from lucide-react {version}.',
             '// ISC license: resources/ui/icons/LUCIDE-LICENSE. Do not edit by hand.',
             'static QPainterPath FrontendIconPath(const QString& Name)', '{', '    QPainterPath Path;']
    for name, filename in sorted(icons.items()):
        module = (PACKAGE / 'dist/esm/icons' / filename).read_text()
        array = re.search(r'createLucideIcon\("[^"]+", (\[.*\])\);', module, re.S).group(1)
        # Lucide icon modules contain declarative arrays of primitives only.
        array = re.sub(r'\b([a-zA-Z]\w*):', r'"\1":', array)
        nodes = json.loads(array)
        commands = []
        for tag, attrs in nodes:
            if tag == 'path':
                pen = QtPen()
                parse_path(attrs['d'], pen)
                commands += pen.lines
            elif tag in {'circle', 'ellipse'}:
                cx, cy = float(attrs['cx']), float(attrs['cy'])
                rx, ry = float(attrs.get('r', attrs.get('rx', 0))), float(attrs.get('r', attrs.get('ry', 0)))
                commands.append(f'Path.addEllipse(QPointF({cx}, {cy}), {rx}, {ry});')
            elif tag == 'rect':
                values = [float(attrs.get(k, 0)) for k in ['x', 'y', 'width', 'height']]
                rx = float(attrs.get('rx', 0))
                ry = float(attrs.get('ry', rx))
                commands.append('Path.addRoundedRect(QRectF(' + ', '.join(map(str, values)) + f'), {rx}, {ry});')
            elif tag == 'line':
                commands += [f'Path.moveTo({attrs["x1"]}, {attrs["y1"]});', f'Path.lineTo({attrs["x2"]}, {attrs["y2"]});']
            elif tag in {'polyline', 'polygon'}:
                points = re.findall(r'[-+]?(?:\d*\.)?\d+', attrs['points'])
                for i in range(0, len(points), 2):
                    commands.append(f'Path.{"moveTo" if i == 0 else "lineTo"}({points[i]}, {points[i+1]});')
                if tag == 'polygon': commands.append('Path.closeSubpath();')
            else:
                raise ValueError(tag)
        lines += [f'    if (Name == QLatin1String("{name}"))', '    {']
        lines += ['        ' + c for c in commands]
        lines += ['        return Path;', '    }']
    lines += ['    return Path;', '}']
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    catalog = ROOT / 'Root/Editor/resources/ui/icons/frontend-icons.json'
    catalog.write_text(json.dumps({'package': 'lucide-react', 'version': version, 'icons': sorted(icons)}, indent=2) + '\n')
    print(f'Imported {len(icons)} frontend vector icons')


if __name__ == '__main__':
    main()
